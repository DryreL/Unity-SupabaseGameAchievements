revoke all on table public.games, public.achievements, public.user_achievements from anon, authenticated;

grant select on table public.games, public.achievements to anon, authenticated;
grant select on table public.user_achievements to authenticated;

-- -----------------------------------------------------------------------------
-- Row Level Security
-- -----------------------------------------------------------------------------

alter table public.games enable row level security;
alter table public.achievements enable row level security;
alter table public.user_achievements enable row level security;

create policy "Active game catalogs are readable"
  on public.games
  for select
  to anon, authenticated
  using (is_active);

create policy "Achievements of active games are readable"
  on public.achievements
  for select
  to anon, authenticated
  using (exists (select 1 from public.games g where g.id = achievements.game_id and g.is_active));

create policy "Users can read their own unlocks"
  on public.user_achievements
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

-- No insert/update/delete policies exist for any client role: those operations are also denied
-- at the grant level above, so a future accidental grant still hits RLS.

-- -----------------------------------------------------------------------------
-- Sync (the only client write path)
-- -----------------------------------------------------------------------------

create or replace function private.sync_achievements(p_game_id bigint, p_achievement_ids bigint[])
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id     uuid := auth.uid();
  v_valid_ids   bigint[];
  v_rejected    bigint[];
  v_existing    bigint[];
  v_new_ids     bigint[];
  v_merged      bigint[];
  v_inserted    integer := 0;
begin
  if v_user_id is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if coalesce(cardinality(p_achievement_ids), 0) > 256 then
    raise exception 'batch_too_large' using errcode = 'P0001', hint = 'Send at most 256 achievement ids per call.';
  end if;

  if p_game_id is null or not exists (select 1 from public.games g where g.id = p_game_id) then
    raise exception 'unknown_game' using errcode = 'P0001';
  end if;

  -- Filter IDs that actually exist in this game and are not retired
  select coalesce(array_agg(a.id order by a.id), '{}')
    into v_valid_ids
    from public.achievements a
   where a.game_id = p_game_id
     and not a.is_retired
     and a.id = any(p_achievement_ids);

  -- Rejected IDs (unknown to game or retired)
  select coalesce(array_agg(distinct req.id order by req.id), '{}')
    into v_rejected
    from unnest(p_achievement_ids) as req(id)
   where req.id is not null
     and not (req.id = any(v_valid_ids));

  -- Get currently unlocked array for this user & game
  select coalesce(ua.achievement_ids, '{}')
    into v_existing
    from public.user_achievements ua
   where ua.user_id = v_user_id
     and ua.game_id = p_game_id;

  if v_existing is null then
    v_existing := '{}';
  end if;

  -- Find newly unlocked IDs not yet in existing array
  select coalesce(array_agg(v.id order by v.id), '{}')
    into v_new_ids
    from unnest(v_valid_ids) as v(id)
   where not (v.id = any(v_existing));

  v_inserted := coalesce(cardinality(v_new_ids), 0);

  -- Merge existing + new (distinct and sorted)
  select coalesce(array_agg(distinct u.id order by u.id), '{}')
    into v_merged
    from unnest(v_existing || v_new_ids) as u(id);

  -- Upsert the single row
  insert into public.user_achievements (user_id, game_id, achievement_ids, updated_at)
  values (v_user_id, p_game_id, v_merged, now())
  on conflict (user_id, game_id) do update set
    achievement_ids = excluded.achievement_ids,
    updated_at = now();

  return jsonb_build_object(
    'accepted', to_jsonb(v_valid_ids),
    'rejected', to_jsonb(v_rejected),
    'inserted', v_inserted
  );
end;
$$;

revoke all on function private.sync_achievements(bigint, bigint[]) from public;
grant execute on function private.sync_achievements(bigint, bigint[]) to authenticated;

create or replace function public.sync_achievements(p_game_id bigint, p_achievement_ids bigint[])
returns jsonb
language sql
security invoker
set search_path = ''
as $$
  select private.sync_achievements(p_game_id, p_achievement_ids);
$$;

comment on function public.sync_achievements(bigint, bigint[]) is
  'Idempotent batched unlock upload for auth.uid(). Returns {accepted[], rejected[], inserted}.';

revoke all on function public.sync_achievements(bigint, bigint[]) from public, anon;
grant execute on function public.sync_achievements(bigint, bigint[]) to authenticated;

-- -----------------------------------------------------------------------------
-- Reconciliation read
-- -----------------------------------------------------------------------------

create or replace function public.get_my_achievements(p_game_id bigint)
returns table (achievement_id bigint, unlocked_at timestamptz)
language sql
stable
security invoker
set search_path = ''
as $$
  select unnest(ua.achievement_ids) as achievement_id,
         ua.updated_at as unlocked_at
    from public.user_achievements ua
   where ua.user_id = (select auth.uid())
     and ua.game_id = p_game_id
   order by achievement_id;
$$;

comment on function public.get_my_achievements(bigint) is
  'Unlocked achievement ids for auth.uid() in one game. RLS-scoped (security invoker).';

revoke all on function public.get_my_achievements(bigint) from public, anon;
grant execute on function public.get_my_achievements(bigint) to authenticated;

-- -----------------------------------------------------------------------------
-- Readable View
-- -----------------------------------------------------------------------------

create or replace view public.user_achievements_readable as
select 
    ua.user_id,
    ua.game_id,
    a.id as achievement_id,
    a.achievement_key,
    a.title as achievement_title,
    ua.updated_at as unlocked_at
from public.user_achievements ua
cross join lateral unnest(ua.achievement_ids) as u(ach_id)
join public.achievements a on a.id = u.ach_id;

grant select on public.user_achievements_readable to authenticated;
